/**
 * OOPSBannerApp UC2 – Banner Display using + operator
 *
 * Prints OOPS in 7-line banner format using
 * string concatenation.
 */

public class OOPSBannerApp {

    public static void main(String[] args) {

        System.out.println("  ***   " + "  ***   " + " ****** " + " ***** ");
        System.out.println(" *   *  " + " *   *  " + " *    * " + " *     ");
        System.out.println(" *   *  " + " *   *  " + " *    * " + " *     ");
        System.out.println(" *   *  " + " *   *  " + " ****** " + " ****  ");
        System.out.println(" *   *  " + " *   *  " + " *      " + "     * ");
        System.out.println(" *   *  " + " *   *  " + " *      " + " *   * ");
        System.out.println("  ***   " + "  ***   " + " *      " + "  ***  ");
    }
}